"""Count how much each candidate talks about specific climate subjects, from their transcripts.

    ONRECORD_DATA_DIR=data/real .venv/bin/python frontend/scripts/theme_metrics.py

Writes frontend/public/themes.json, which the candidate page's "Climate integrity score" reads.
Everything here is a count over the committed transcripts, so the same words always give the
same numbers. It measures how much and how concretely a subject comes up in a candidate's
videos. It does not judge whether what was said is good or bad for the climate, and a
transcript also contains interviewers' and opponents' words, so treat it as "modeled".

Per subject, for one candidate:
  breadth       share of their searched videos where the subject comes up
  depth         mentions per hour of video, capped at DEPTH_CAP
  concreteness  share of the mentions that sit next to an action, rule or number
  value         100 * (0.4 * breadth + 0.3 * depth + 0.3 * concreteness)
The overall number is the average of the subjects. Candidates with fewer than MIN_VIDEOS
searched videos get no numbers.
"""
from __future__ import annotations

import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / "backend"))

import config  # noqa: E402
import storage  # noqa: E402

OUT = ROOT / "frontend" / "public" / "themes.json"
MIN_VIDEOS = 3
DEPTH_CAP = 6.0  # mentions per hour that count as "talks about it a lot"

THEMES = [
    ("ai_data_centers", "AI & data centers", r"data cent(?:er|re)s?|hyperscale|artificial intelligence|\bA\.?I\.?\b"),
    ("emissions", "Emissions", r"climate|greenhouse|emissions?|carbon|pollution|global warming|fossil fuels?"),
    ("clean_energy", "Clean energy", r"renewables?|solar|wind (?:power|energy|farm)|clean (?:energy|power)|nuclear|batter(?:y|ies)"),
    ("water", "Water", r"\bwater\b|aquifers?|drought"),
    ("energy_bills", "Energy bills", r"utility (?:rates?|bills?)|electric(?:ity)? (?:rates?|bills?|prices?)|power bills?|ratepayers?|energy (?:costs?|bills?|prices?)"),
]
ACTION = re.compile(
    r"\b(will|won't|would|must|require[sd]?|ban|moratorium|pause|permits?|law|bill|veto|sign|vote[d]?|pledge|"
    r"guardrails?|protections?|standards?|invest|build|percent|\d+)\b", re.I)


def main() -> None:
    data_dir = config.data_dir()
    videos = storage.load_videos(data_dir)
    out = {"_note": "Generated by frontend/scripts/theme_metrics.py from the committed transcripts. Counts, not judgments.",
           "themes": [{"id": i, "label": label} for i, label, _ in THEMES], "candidates": {}}
    for cand in storage.load_candidates(data_dir):
        texts = []  # one list of segment texts per searched video
        hours = 0.0
        for v in videos:
            if v.candidate_id != cand.id:
                continue
            t = storage.load_transcript(v, data_dir)
            if t and t.segments:
                texts.append([s.text for s in t.segments])
                hours += (v.duration_sec or 0) / 3600
        if len(texts) < MIN_VIDEOS:
            out["candidates"][cand.id] = None
            continue
        themes = {}
        for tid, _, pattern in THEMES:
            rx = re.compile(pattern, re.I)
            mentions = concrete = with_theme = 0
            for segs in texts:
                hit = False
                for n, text in enumerate(segs):
                    if not rx.search(text):
                        continue
                    hit = True
                    mentions += 1
                    window = " ".join(segs[max(0, n - 1): n + 2])  # the line before and after too
                    concrete += bool(ACTION.search(window))
                with_theme += hit
            breadth = with_theme / len(texts)
            depth = min(1.0, (mentions / hours) / DEPTH_CAP) if hours else 0.0
            concreteness = concrete / mentions if mentions else 0.0
            themes[tid] = {"value": round(100 * (0.4 * breadth + 0.3 * depth + 0.3 * concreteness)),
                           "mentions": mentions, "videos": with_theme}
        out["candidates"][cand.id] = {
            "overall": round(sum(t["value"] for t in themes.values()) / len(themes)),
            "videos": len(texts), "hours": round(hours, 1), "themes": themes}
    OUT.write_text(json.dumps(out, indent=1) + "\n", encoding="utf-8")
    for cid, c in out["candidates"].items():
        print(cid, "-" if c is None else f"{c['overall']} " + " ".join(f"{k}={v['value']}({v['mentions']})" for k, v in c["themes"].items()))


if __name__ == "__main__":
    main()
